"""Generate crates/rustuml-render/src/font_chain_coverage.rs from FontChainExtract.swift output.

Usage: python3 -I tools/font_chain_coverage.py <out.rs> <Face>=<extract.tsv> ...
Face names are the generated constants font_chain::ChainFace reads; identical run tables are shared
between faces.
"""
import sys

def load(path):
    header, runs = [], {"S": [], "C": []}
    for line in open(path, encoding="utf-8"):
        fields = line.rstrip("\n").split("\t")
        if fields[0].startswith("#"):
            header.append(fields)
        else:
            runs[fields[0]].append((int(fields[1], 16), int(fields[2], 16)))
    return header, {k: sorted(v) for k, v in runs.items()}


def table(runs):
    rows, line = [], []
    for a, b in runs:
        line.append(f"(0x{a:X}, 0x{b:X})")
        if len(line) == 6:
            rows.append("    " + ", ".join(line) + ",")
            line = []
    if line:
        rows.append("    " + ", ".join(line) + ",")
    return "\n".join(rows)


out_path, specs = sys.argv[1], [a.split("=", 1) for a in sys.argv[2:]]
faces, tables, counts = [], {}, {"S": 0, "C": 0}
for face, path in specs:
    header, runs = load(path)
    info = {h[0]: h[1:] for h in header}
    notdef = float(info["#notdef_advance_units"][0])
    upem = int(info["#notdef_advance_units"][2])
    assert upem == 2048 and notdef == int(notdef), (face, notdef, upem)
    names = []
    for kind, kind_runs in (("S", runs["S"]), ("C", runs["C"])):
        key = (kind, tuple(kind_runs))
        if key not in tables:
            counts[kind] += 1
            tables[key] = f"{'SIMPLE_MISSING' if kind == 'S' else 'COMPLEX_MAPPED'}_{counts[kind]}"
        names.append(tables[key])
    faces.append((face, int(notdef), names, info["#family"][1], info["#family"][2], info["#host"][0]))

hosts = sorted({f[5] for f in faces})
lines = [
    "// Copyright 2026 Marcelo Cantos",
    "// SPDX-License-Identifier: Apache-2.0",
    "",
    "// Generated by tools/FontChainExtract.swift (CoreText on the origin Mac, system fonts only) and",
    "// tools/font_chain_coverage.py; do not edit by hand. Host: " + "; ".join(hosts) + ".",
    "// Per face: the .notdef advance in 2048ths of an em (glyph 0 of the primary font,",
    "// CTFontGetAdvancesForGlyphs), the BMP runs the JDK simple path cannot map, and the runs the",
    "// complex path (CFont.createCompositeFont cascade) maps.",
    "",
    "use crate::font_chain::FaceCoverage;",
    "",
]
for (kind, key), name in tables.items():
    lines.append(f"const {name}: &[(u32, u32)] = &[")
    if key:
        lines.append(table(key))
    lines.append("];")
    lines.append("")
for face, notdef, (s_name, c_name), family, font_path, _ in faces:
    lines.append(f"/// {family}, {font_path}.")
    lines.append(f"pub(crate) const {face}: FaceCoverage = FaceCoverage {{")
    lines.append(f"    notdef_units: {notdef},")
    lines.append(f"    simple_missing: {s_name},")
    lines.append(f"    complex_mapped: {c_name},")
    lines.append("};")
open(out_path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(len(faces), "faces,", len(tables), "tables,", sum(len(k[1]) for k in tables), "runs")
