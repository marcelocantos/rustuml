"""Generate crates/rustuml-render/src/font_chain_unicode.rs from Unicode Character Database files.

Usage: python3 -I tools/font_chain_unicode.py <out.rs> <Scripts-3.2.0.txt> <UnicodeData-16.0.0.txt> [ScriptRunData.java]

* NONSPACING_MARKS: general category Mn in Unicode 16.0.0, the UCD of HarfBuzz 10.0.1 (the library
  the reference JDK's libfontmanager links), which hb_synthesize_glyph_classes and
  zero_mark_advances read; UNICODE_MARKS: Mn, Mc and Me (_hb_glyph_info_is_unicode_mark, the
  cluster rule of _hb_ot_shape_fallback_mark_position).
* SCRIPTS: the strong scripts of Unicode 3.2.0 Scripts.txt as ICU UScriptCode values 2..45; Common,
  Inherited and unassigned code points are absent (weak). JDK 21's sun.font.ScriptRunData equals this
  file for every code point; pass ScriptRunData.java to re-check that equality while generating.
* COMPLEX_SHAPED_SCRIPTS: the ICU codes whose HarfBuzz script hb_ot_shaper_categorize (hb-ot-shaper.hh)
  gives a shaper other than the default one when the face has no GSUB (chosen script NONE);
  FALLBACK_POSITIONED_SCRIPTS: those whose shaper has fallback_position (arabic, hebrew).
"""
import bisect, hashlib, re, sys

out_path, scripts_path, unicode_data_path = sys.argv[1:4]
jdk_path = sys.argv[4] if len(sys.argv) > 4 else None

# ICU UScriptCode 0..45 (the codes JDK's scriptMapping.c ICU_to_Harfbuzz_ScriptCode maps).
ICU = ("COMMON INHERITED ARABIC ARMENIAN BENGALI BOPOMOFO CHEROKEE COPTIC CYRILLIC DESERET DEVANAGARI "
       "ETHIOPIC GEORGIAN GOTHIC GREEK GUJARATI GURMUKHI HAN HANGUL HEBREW HIRAGANA KANNADA KATAKANA KHMER "
       "LAO LATIN MALAYALAM MONGOLIAN MYANMAR OGHAM OLD_ITALIC ORIYA RUNIC SINHALA SYRIAC TAMIL TELUGU THAANA "
       "THAI TIBETAN CANADIAN_ABORIGINAL YI TAGALOG HANUNOO BUHID TAGBANWA").split()
# hb_ot_shaper_categorize with chosen_script NONE: Arabic/Syriac -> arabic; Thai/Lao -> thai; Hangul;
# Hebrew; the nine Indic scripts -> indic; Khmer; Myanmar -> myanmar; Tibetan, Mongolian, Sinhala,
# Buhid, Hanunoo, Tagalog, Tagbanwa -> USE. Everything else (Thaana included) -> default.
COMPLEX = ["ARABIC", "SYRIAC", "THAI", "LAO", "HANGUL", "HEBREW", "BENGALI", "DEVANAGARI", "GUJARATI",
           "GURMUKHI", "KANNADA", "MALAYALAM", "ORIYA", "TAMIL", "TELUGU", "KHMER", "MYANMAR", "TIBETAN",
           "MONGOLIAN", "SINHALA", "BUHID", "HANUNOO", "TAGALOG", "TAGBANWA"]
# Shapers with fallback_position true (HarfBuzz 10.0.1): default, arabic (Arabic, Syriac), hebrew.
FALLBACK_POSITIONED = ["ARABIC", "SYRIAC", "HEBREW"]


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


script = {}
for line in open(scripts_path, encoding="utf-8"):
    line = line.split("#")[0].strip()
    if not line:
        continue
    cps, name = [x.strip() for x in line.split(";")]
    first, last = (cps.split("..") + [cps])[:2]
    code = ICU.index(name.upper())
    for cp in range(int(first, 16), int(last, 16) + 1):
        script[cp] = code

if jdk_path:
    body = re.sub(r"//[^\n]*", "", re.search(r"private static final int\[\] data\s*=\s*\{(.*?)\};",
                                             open(jdk_path).read(), re.S).group(1))
    nums = [int(x, 16) if x.lower().startswith("0x") else int(x) for x in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", body)]
    starts, codes = nums[0::2], nums[1::2]
    diff = sum(1 for cp in range(0x110000) if codes[bisect.bisect_right(starts, cp) - 1] != script.get(cp, 0))
    assert diff == 0, f"ScriptRunData differs from Scripts-3.2.0 on {diff} code points"

strong = []
for cp in sorted(script):
    code = script[cp]
    if code <= 1:
        continue
    if strong and strong[-1][1] + 1 == cp and strong[-1][2] == code:
        strong[-1][1] = cp
    else:
        strong.append([cp, cp, code])

def category_runs(categories):
    runs = []
    for line in open(unicode_data_path, encoding="utf-8"):
        fields = line.split(";")
        if fields[2] not in categories:
            continue
        assert not fields[1].endswith(", First>"), fields
        cp = int(fields[0], 16)
        if runs and runs[-1][1] + 1 == cp:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp])
    return runs


marks = category_runs({"Mn"})
unicode_marks = category_runs({"Mn", "Mc", "Me"})


def rows(items, fmt, per_line):
    out, line = [], []
    for item in items:
        line.append(fmt(item))
        if len(line) == per_line:
            out.append("    " + ", ".join(line) + ",")
            line = []
    if line:
        out.append("    " + ", ".join(line) + ",")
    return "\n".join(out)


text = f"""// Copyright 2026 Marcelo Cantos
// SPDX-License-Identifier: Apache-2.0

// Generated by tools/font_chain_unicode.py; do not edit by hand.
// Sources (https://www.unicode.org/Public/):
//   3.2-Update/Scripts-3.2.0.txt sha256 {sha(scripts_path)}
//   16.0.0/ucd/UnicodeData.txt sha256 {sha(unicode_data_path)}

/// General category Mn in Unicode 16.0.0 (HarfBuzz 10.0.1's UCD).
pub(crate) const NONSPACING_MARKS: &[(u32, u32)] = &[
{rows(marks, lambda r: f"(0x{r[0]:X}, 0x{r[1]:X})", 6)}
];

/// General categories Mn, Mc and Me in Unicode 16.0.0.
pub(crate) const UNICODE_MARKS: &[(u32, u32)] = &[
{rows(unicode_marks, lambda r: f"(0x{r[0]:X}, 0x{r[1]:X})", 6)}
];

/// Strong scripts of Unicode 3.2.0 (equal to JDK 21's `ScriptRunData`) as ICU
/// `UScriptCode` values; absent code points are Common, Inherited or
/// unassigned.
pub(crate) const SCRIPTS: &[(u32, u32, u8)] = &[
{rows(strong, lambda r: f"(0x{r[0]:X}, 0x{r[1]:X}, {r[2]})", 4)}
];

/// ICU codes whose HarfBuzz shaper is not the default one for a face without
/// GSUB (`hb_ot_shaper_categorize`, chosen script NONE).
pub(crate) const COMPLEX_SHAPED_SCRIPTS: &[u8] = &[{", ".join(str(ICU.index(n)) for n in sorted(COMPLEX, key=ICU.index))}];

/// Of those, the ICU codes whose shaper positions marks by fallback
/// (`fallback_position`: arabic, hebrew).
pub(crate) const FALLBACK_POSITIONED_SCRIPTS: &[u8] = &[{", ".join(str(ICU.index(n)) for n in sorted(FALLBACK_POSITIONED, key=ICU.index))}];
"""
open(out_path, "w", encoding="utf-8").write(text)
print(len(marks), "Mn runs,", len(unicode_marks), "mark runs,", len(strong), "script runs")
